/**
 * Writes the change-log triggers for every synced table (src/sync/tables.ts)
 * into a migration file. Each insert, update or delete records the row's key
 * and the time in sync_changes. Rows written by sync itself are recorded too,
 * and removed by the sync engine afterwards (see src/sync/engine.ts).
 *
 *   node scripts/sync-triggers.mjs drizzle/0003_sync_triggers.sql
 */
import { writeFileSync } from 'node:fs';

import { SYNCED_TABLES } from '../src/sync/tables.ts';

const out = process.argv[2];
if (!out) throw new Error('usage: node scripts/sync-triggers.mjs <migration.sql>');

const NOW_MS = "CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER)";

const statements = [];
for (const { name, key } of SYNCED_TABLES) {
  for (const [event, ref] of [['INSERT', 'NEW'], ['UPDATE', 'NEW'], ['DELETE', 'OLD']]) {
    statements.push(
      `CREATE TRIGGER IF NOT EXISTS sync_${name}_${event.toLowerCase()} AFTER ${event} ON ${name} BEGIN\n` +
        `  INSERT INTO sync_changes (tbl, row_key, changed_at) VALUES ('${name}', ${ref}.${key}, ${NOW_MS});\n` +
        `END;`,
    );
  }
  // What's already on this device goes up on the first sync.
  statements.push(`INSERT INTO sync_changes (tbl, row_key, changed_at) SELECT '${name}', ${key}, ${NOW_MS} FROM ${name};`);
}

writeFileSync(
  out,
  `-- Generated by scripts/sync-triggers.mjs from src/sync/tables.ts. Don't edit by hand.\n` +
    statements.join('\n--> statement-breakpoint\n') +
    '\n',
);
console.log(`wrote ${statements.length} statements to ${out}`);
